# -*- coding: utf-8 -*-

from datetime import date, datetime

from odoo.fields import Command
from odoo.tests.common import TransactionCase, tagged


@tagged('post_install', '-at_install')
class TestPublicHolidayBackfill(TransactionCase):

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.company = cls.env.company
        cls.calendar = cls.env['resource.calendar'].create({'name': 'Backfill 40h', 'company_id': cls.company.id})
        cls.employee = cls.env['hr.employee'].create({
            'name': 'Backfill Employee', 'company_id': cls.company.id,
            'resource_calendar_id': cls.calendar.id,
        })
        # Created without entries, like the holidays imported in 2023.
        cls.holiday = cls.env['resource.calendar.leaves'].with_context(skip_gen=True).create({
            'name': 'Backfill Holiday', 'calendar_id': cls.calendar.id, 'company_id': cls.company.id,
            'date_from': datetime(2030, 11, 11, 0, 0), 'date_to': datetime(2030, 11, 11, 23, 0),
        })
        cls.Line = cls.env['account.analytic.line']
        cls.Line.search([('global_leave_id', '=', cls.holiday.id)]).write({'global_leave_id': False})
        cls.Line.search([('employee_id', '=', cls.employee.id)]).unlink()
        cls.day = date(2030, 11, 11)

    def _holiday_lines(self):
        return self.Line.search([('employee_id', '=', self.employee.id), ('global_leave_id', '=', self.holiday.id)])

    def _backfill(self, since=date(2030, 1, 1)):
        return self.env['resource.calendar.leaves']._backfill_public_holiday_timesheets(since)

    def test_missing_entry_is_added_once(self):
        self._backfill()
        line = self._holiday_lines()
        self.assertEqual(line.date, self.day)
        self.assertEqual(line.unit_amount, 8)
        self._backfill()
        self.assertEqual(len(self._holiday_lines()), 1)

    def test_days_before_start_are_not_touched(self):
        self._backfill(since=date(2030, 11, 12))
        self.assertFalse(self._holiday_lines())

    def test_zeroed_hours_are_not_recreated(self):
        self._backfill()
        self._holiday_lines().unit_amount = 0
        skip = self.env['public.holiday.timesheet.skip'].search([('employee_id', '=', self.employee.id)])
        self.assertEqual(skip.date, self.day)
        self._backfill()
        self.assertEqual(self._holiday_lines().unit_amount, 0)
        # Nor when the employee's entries are regenerated by a calendar change.
        other = self.calendar.copy({'name': 'Backfill other'})
        self.employee.resource_calendar_id = other
        self.employee.resource_calendar_id = self.calendar
        self.assertFalse(self._holiday_lines())
        self._backfill()
        self.assertFalse(self._holiday_lines())
        # Removing the mark lets it come back.
        skip.unlink()
        self._backfill()
        self.assertEqual(self._holiday_lines().unit_amount, 8)

    def test_restoring_hours_clears_the_mark(self):
        self._backfill()
        line = self._holiday_lines()
        line.unit_amount = 0
        line.unit_amount = 8
        self.assertFalse(self.env['public.holiday.timesheet.skip'].search([('employee_id', '=', self.employee.id)]))

    def test_regeneration_does_not_create_skip_marks(self):
        self._backfill()
        other = self.calendar.copy({'name': 'Backfill other'})
        self.employee.resource_calendar_id = other
        self.assertFalse(self.env['public.holiday.timesheet.skip'].search([('employee_id', '=', self.employee.id)]))

    def test_day_with_work_is_skipped(self):
        project = self.company.internal_project_id
        self.Line.create({'name': 'Worked abroad', 'project_id': project.id, 'employee_id': self.employee.id,
                          'date': self.day, 'unit_amount': 8})
        self._backfill()
        self.assertFalse(self._holiday_lines())

    def test_approved_sheet_is_skipped(self):
        self.employee.user_id = self.env['res.users'].create({
            'name': 'bf', 'login': 'bf_user', 'groups_id': [Command.set([self.env.ref('base.group_user').id])]})
        sheet = self.env['hr_timesheet.sheet'].create({
            'employee_id': self.employee.id, 'company_id': self.company.id,
            'date_start': date(2030, 11, 11), 'date_end': date(2030, 11, 17),
        })
        sheet.state = 'done'
        self._backfill()
        self.assertFalse(self._holiday_lines())
