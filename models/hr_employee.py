# -*- coding: utf-8 -*-

from collections import defaultdict

from odoo import fields, models


class HrEmployee(models.Model):
    _inherit = 'hr.employee'

    def _create_future_public_holidays_timesheets(self, employees):
        """Full override of project_timesheet_holidays' method: it builds
        the per-day work-hours list correctly for the create-lines loop
        (`work_hours_data[employee.resource_calendar_id.id][global_time_off.id]`)
        but then passes a shallower, wrongly-keyed lookup
        (`work_hours_data[global_time_off.id]`, missing the calendar level)
        into _timesheet_prepare_line_values just to compute len(...) for the
        "(x/y)" label. Since work_hours_data is a nested defaultdict, that
        wrong key auto-vivifies an empty value, so every line generated by
        this method is mislabeled "(x/0)" regardless of the real day count.

        Fix: reuse the same correctly-keyed list for both the loop and the
        label, instead of re-deriving it a second, wrong way.
        """
        lines_vals = []
        today = fields.Datetime.today()
        global_leaves_wo_calendar = defaultdict(lambda: self.env["resource.calendar.leaves"])
        global_leaves_wo_calendar.update(dict(self.env['resource.calendar.leaves']._read_group(
            [('calendar_id', '=', False), ('date_from', '>=', today)],
            groupby=['company_id'],
            aggregates=['id:recordset'],
        )))
        # Days the employee removed the holiday entry on purpose stay removed
        # when the entries are regenerated (calendar change, unarchive).
        skipped = {
            (skip.employee_id.id, skip.date)
            for skip in self.env['public.holiday.timesheet.skip'].sudo().search([('employee_id', 'in', employees.ids)])
        }
        for employee in employees:
            if not employee.active:
                continue
            global_leaves = employee.resource_calendar_id.global_leave_ids.filtered(
                lambda l: l.date_from >= today
            ) + global_leaves_wo_calendar[employee.company_id]
            work_hours_data = global_leaves._work_time_per_day()
            for global_time_off in global_leaves:
                per_day = work_hours_data[employee.resource_calendar_id.id][global_time_off.id]
                for index, (day_date, work_hours_count) in enumerate(per_day):
                    if (employee.id, day_date) in skipped:
                        continue
                    lines_vals.append(
                        global_time_off._timesheet_prepare_line_values(
                            index,
                            employee,
                            per_day,
                            day_date,
                            work_hours_count,
                        )
                    )
        return self.env['account.analytic.line'].sudo().create(lines_vals)
